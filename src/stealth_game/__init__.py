"""スニーキューブ（SNEAKUBE）：Panda3D ステルスゲーム（A*で動く警備員）

実行方法:
    uv run stealth-game
    （または python -m stealth_game）

遊び方:
    WASD / 矢印キー : 移動
    Shift           : 忍び足（足音が消え、見つかりにくくなる）
    E / .           : お助けアイテム「透明化」を使う
    Q / /           : お助けアイテム「スタン」を使う
    Space / \\       : お助けアイテム「音の罠」を足元に設置
    Tab             : 視点の切り替え（全体 → 中間 → 近い → 全体 …）
    F               : 設定：走ったときに足音の届く範囲の表示のオン・オフ
    P               : 一時停止・再開（タイムアタックでは使えない）
    V               : 難易度選択の画面で、ベスト記録を再生／クリアした画面で、今のプレイを再生
    R               : 同じ難易度でリスタート
    M               : 難易度選択に戻る
    Esc             : 終了

ルール:
    40×40のマップに散らばる8個のアイテムを全て集め、右上の出口へ向かおう。
    最初はマップ全体が見える表示で始まる（Tabを押すごとに 中間 → 近い → 全体 と切り替わる）。
    スタート地点は、左下の部屋から左へ出っ張った小部屋。ここは安全地帯（見つからず、
    鬼も入れない）。一度出ると扉が閉まり戻れない。
    警備員は視界（扇形）にあなたが入り続けると気づき、「！」を出して追跡してくる。
    走ると足音で近くの警備員に気づかれる。
    追跡中の警備員は進行方向を先読みして先回りし、見失っても逃げた方向を探す。
    青は決まった順路を巡回、紫は順路がなく、ランダムに歩き回る。

    お助けアイテム（地獄以外）: 種類ごとに20秒おきにマップに箱が出る。拾うと持ち歩ける。
    （スタンは簡単・普通だけ。難しい・激ムズは透明化と音の罠の2種）
      透明化（白）  : E（.）で使うと10秒間、警備員の視界に映らず、触れても捕まらない。
                      足音は聞かれる。1個まで持てる。効果中は使えないが、切れたらすぐ次を使える。
      スタン（ピンク）: Q（/）ですぐに光る。その瞬間あなたを視界に入れていた警備員は10秒間、
                      それ以外でも周囲12マス以内（壁越しも含む）の警備員は5秒間、
                      目がくらんで動けない（その間は触れても捕まらない）。
                      目が覚めると、あなたを見失って最後に見た場所を調べに行く。1個まで持てる。
      音の罠（水色）: Space（\\）で床に置くと、数秒後に大きな音を出し、範囲内の警備員が
                      そこへ調べに行く（追跡中でも、あなたを見ていなければ引きつけられる）。2個まで持てる。
    全アイテム回収後に見失わず追ってくる紫の警備員には、お助けアイテムは効かない。

    ライフ（簡単・普通のみ）: 捕まるとライフが1減り、アイテムを2個その場に落として
    スタート地点へ戻される。このとき警備員も全員、最初の位置と状態に戻る。
    ライフが0、またはライフのない難易度で捕まるとゲームオーバー。

難易度:
    簡単   : 「普通」から紫の鬼（徘徊型）をなくしたもの。ライフ3。
    普通   : 基本の難しさ。ライフ2。
    難しい : 「激ムズ」の視界を弱め、紫の鬼が注目地点に来る確率を下げ、
             足音での察知を大幅に下げ、「応援」を軽く（近くの2人まで）したもの。
    激ムズ : 「地獄」から追跡速度を1割落とし、「！」の後に0.5秒の間を置き、
             お助けアイテム（透明化・音の罠）を加えたもの。
    地獄   : 全力の警備員。「！」と同時に追跡し、お助けアイテムもない。
             紫の鬼はプレイヤー・未回収のアイテム・出口の付近を優先して歩き回り、
             全アイテムを集めると、プレイヤーを決して見失わずに追いかけてくる。
    超越   : 地獄より見つかりやすく、見張り番・監視カメラ・時間で開け閉めする扉・鳴る床がある。
    タイムアタック : 警備員もお助けアイテムもなし。8個集めて出口までのタイムを競う。
             再生では、同じ配置を攻略ボットに解かせたゴーストが一緒に走る。
    （追跡速度は、地獄・超越4.4、難しい・激ムズ3.96、普通・簡単3.1。
      地獄・超越以外は「！」の後に0.5秒の間がある）
    激ムズ以上では、遠くにいる追っ手（応援で呼ばれた鬼を含む）が、近い鬼の通る道を
    避けて回り込み、逃げる先へ先回りしてくる（挟み撃ち）。
"""


def main() -> None:
    from .app.game import StealthGame

    StealthGame().run()
