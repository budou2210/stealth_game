"""試験用の切り替えスイッチ。環境変数 BOT_OPTIONS に、使う工夫の記号をカンマ区切りで書く（例: BOT_OPTIONS=C,D）。

- A: 配置を選ぶとき、アイテムを回る道のりが短い配置を優先する
- S2: 滑らかに動くとき、2区切り先まで近道する（標準は1区切り先まで）
- C: 時間と場所の経路で、同じくらい目標に近づけるなら、早く着ける経路を選ぶ
- D: アイテムを集める順番を、全体の道のりが短くなるように組み替える
- T: 1区切りを約0.47秒に短くして、忍び足の速さを無駄なく使う
- V: 速度重視（成功率は下がってよい）。足音を気にせず、見られない限り走る。同じくらい近づけるなら早く着く経路を選ぶ（C を含む）
（E「余裕を小さくする」は効果が大きかったので標準にした。C・D・T はタイムが縮まなかったので標準にはしていない）

地獄を速くするための試験（2026-11-07）。--fast を付けると、FAST_OPTIONS に入れたものをまとめて使う：
- F1: アイテムを取る順番を、全部の順番を比べて一番短いものにする（最後のアイテムも含めて選ぶ）
- F2: 時間と場所の経路で、走るときに斜め（1,1）と桂馬（2,1）の動きも使う
- F3: 同じくらい近づけるなら走る経路を選ぶ。足音の余裕を小さくする
- F4: 目標に届く経路が複数あるとき、一番早く届くものを選ぶ
- F5: refine で、やり直す時点を細かく（2.5秒ごと・16か所）し、アイテムを拾った直後からもやり直す
- F6: 何度も見つかる場所を避ける（超越用の工夫を地獄でも使う）
- F7: 視界の余裕をさらに小さくする
- F8: 確かめで経路がだめだったら、別の経路を探し直す（最大2回）
- F9: 危険度の重みを変える（DANGER_WEIGHT）
"""

import os

FAST_ENV = "BOT_FAST"
# --fast のときに使う工夫。F1（順番）は、同じ配置を使う・使わないの両方で試す（run.py・refine.py）。
# 32配置での試験の結果（基準 27/32 クリア・平均154.1秒・最速57.23秒）：
# F4+F7 と F1+F4+F7 の速いほう → 31/32・平均133.2秒・中央値111.5秒・最速46.10秒（計算は約1.7倍）。
# F5（refine の細かいやり直し）は、410 の記録を 46.07 → 45.63秒に縮めた（今のやり方では縮まなかった）。
# F2・F3・F6・F8・F9 は遅くなったので使わない
FAST_OPTIONS = ("F4", "F5", "F7")
ENABLED = {name.strip().upper() for name in os.environ.get("BOT_OPTIONS", "").split(",") if name.strip()}


def is_fast():
    """--fast（速さを詰める動き）で動いているか。"""
    return os.environ.get(FAST_ENV) == "1"


def set_fast(on):
    if on:
        os.environ[FAST_ENV] = "1"
    else:
        os.environ.pop(FAST_ENV, None)


def enabled(name):
    return name in ENABLED or (is_fast() and name in FAST_OPTIONS)
